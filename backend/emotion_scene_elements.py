# Utility function to get details for any complex word
def get_details_for_complex_word(word):
    raw = str(word or "").strip().lower()
    if not raw:
        return None

    candidates = [
        raw,
        raw.replace("_", "-"),
        raw.replace(" ", "-"),
        raw.replace("-", " "),
    ]
    for key in candidates:
        details = COMPLEX_WORD_DETAILS.get(key)
        if details:
            return details
    return None
